static lv_obj_t *_container(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h)
{
    auto obj = lv_obj_create(parent);
    lv_obj_set_pos(obj, x, y);
    if (w != LV_SIZE_CONTENT && h != LV_SIZE_CONTENT) {
        lv_obj_set_size(obj, w, h);
    }
    lv_obj_clear_flag(obj, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_set_style_bg_opa(obj, LV_OPA_TRANSP, LV_PART_MAIN);
    lv_obj_set_style_border_width(obj, 0, LV_PART_MAIN);
    lv_obj_set_style_radius(obj, 0, LV_PART_MAIN);
    lv_obj_set_style_pad_all(obj, 0, LV_PART_MAIN);
    return obj;
}

static lv_obj_t *_disc(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t d, uint32_t color,
                       lv_opa_t opa = LV_OPA_COVER)
{
    auto obj = _container(parent, x, y, d, d);
    lv_obj_set_style_radius(obj, LV_RADIUS_CIRCLE, LV_PART_MAIN);
    lv_obj_set_style_bg_color(obj, lv_color_hex(color), LV_PART_MAIN);
    lv_obj_set_style_bg_opa(obj, opa, LV_PART_MAIN);
    return obj;
}

