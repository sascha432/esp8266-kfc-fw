KeyValueRefs addKeyValue(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t gap,
                         const char *key, const char *value, lv_coord_t keyWidth)
{
    KeyValueRefs refs;
    // the key never takes more than half of the row, a longer key is cut off
    const auto maxKeyWidth = static_cast<lv_coord_t>((w - gap) / 2);
    if (keyWidth <= 0) {
        keyWidth = static_cast<lv_coord_t>((w - gap) * 0.45f);
    }
    if (keyWidth > maxKeyWidth) {
        keyWidth = maxKeyWidth;
    }
    auto valueWidth = static_cast<lv_coord_t>(w - gap - keyWidth);
    refs.key = addLabel(parent, x, y, key, kFontNormal, kColorTextLabel, keyWidth);
    fitTextDown(refs.key, key, keyWidth);
    refs.value = addLabel(parent, static_cast<lv_coord_t>(x + keyWidth + gap), y, value, kFontNormal,
                          kColorText, valueWidth, LV_TEXT_ALIGN_RIGHT);
    // the value shrinks first, but it must not grow either: the rows of a key/value list are
    // already laid out and mixing font sizes looks broken (the row height is fixed)
    fitTextDown(refs.value, value, valueWidth);
    // a row is one line, a long value must be cut off instead of wrapping into the next row
    lv_obj_set_height(refs.key, lv_font_get_line_height(kFontNormal));
    lv_obj_set_height(refs.value, lv_font_get_line_height(kFontNormal));
    return refs;
}

