// vertical position of the clock in the top bar and the gap between its labels
static constexpr lv_coord_t kClockTop = 4;
static constexpr lv_coord_t kClockGap = 10;
static constexpr lv_coord_t kClockMargin = 10;
// room for the title on the left side of the top bar (a longer title shrinks)
static constexpr lv_coord_t kTitleWidth = 150;
// the info text starts here and ends before the clock
static constexpr lv_coord_t kInfoX = 168;
static constexpr lv_coord_t kClockReserve = 240;

// places date, time and the time zone next to each other at the right end of the top bar. The
// date and the time zone are baseline aligned with the (larger) time
void _alignClock(const PageRefs &page)
{
    if (!page.date || !page.time || !page.zone) {
        return;
    }
    const auto dateWidth = getTextWidth(lv_label_get_text(page.date), kFontNormal);
    const auto timeWidth = getTextWidth(lv_label_get_text(page.time), kFontTitle);
    const auto zoneWidth = getTextWidth(lv_label_get_text(page.zone), kFontNormal);
    auto x = static_cast<lv_coord_t>(lv_disp_get_hor_res(nullptr) - kClockMargin -
                                     (dateWidth + kClockGap + timeWidth + kClockGap + zoneWidth));
    const auto titleTop = static_cast<lv_coord_t>(kClockTop + _baseline(kFontTitle) - _baseline(kFontNormal));

    lv_obj_set_pos(page.date, x, titleTop);
    x = static_cast<lv_coord_t>(x + dateWidth + kClockGap);
    lv_obj_set_pos(page.time, x, kClockTop);
    x = static_cast<lv_coord_t>(x + timeWidth + kClockGap);
    lv_obj_set_pos(page.zone, x, titleTop);
}

PageRefs createPage(lv_obj_t *parent, const char *title, const char *right)
{
    PageRefs page;
    if (!parent) {
        return page;
    }
    page.root = parent;
    lv_obj_clear_flag(parent, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_set_style_bg_color(parent, lv_color_hex(kColorBackground), LV_PART_MAIN);
    lv_obj_set_style_bg_opa(parent, LV_OPA_COVER, LV_PART_MAIN);
    lv_obj_set_style_pad_all(parent, 0, LV_PART_MAIN);

    // top bar: title on the left, clock on the right
    auto bar = _container(parent, 0, 0, LV_PCT(100), kBarHeight);
    lv_obj_set_style_bg_color(bar, lv_color_hex(kColorBar), LV_PART_MAIN);
    lv_obj_set_style_bg_opa(bar, LV_OPA_COVER, LV_PART_MAIN);
    lv_obj_set_style_border_side(bar, LV_BORDER_SIDE_BOTTOM, LV_PART_MAIN);
    lv_obj_set_style_border_width(bar, 1, LV_PART_MAIN);
    lv_obj_set_style_border_color(bar, lv_color_hex(kColorTextMuted), LV_PART_MAIN);
    lv_obj_set_style_border_opa(bar, LV_OPA_50, LV_PART_MAIN);
    lv_obj_set_width(bar, lv_disp_get_hor_res(nullptr));
    // the screen manager handles the taps of the bar (they open the screen overview), no widget
    // inside it needs to be clickable
    lv_obj_clear_flag(bar, LV_OBJ_FLAG_CLICKABLE);

    page.title = lv_label_create(bar);
    lv_obj_set_style_text_font(page.title, kFontMedium, LV_PART_MAIN);
    lv_obj_set_style_text_color(page.title, lv_color_hex(kColorTextLabel), LV_PART_MAIN);
    lv_obj_set_width(page.title, kTitleWidth);
    lv_label_set_text(page.title, title ? title : "");
    fitTextDown(page.title, title ? title : "", kTitleWidth);
    lv_obj_align(page.title, LV_ALIGN_LEFT_MID, 10, 0);

    if (right) {
        page.info = lv_label_create(bar);
        lv_obj_set_style_text_font(page.info, kFontSmall, LV_PART_MAIN);
        lv_obj_set_style_text_color(page.info, lv_color_hex(kColorTextMuted), LV_PART_MAIN);
        // one line between the title and the clock, a longer text is cut off
        fitTextDown(page.info, right, static_cast<lv_coord_t>(lv_disp_get_hor_res(nullptr) - kClockReserve - kInfoX));
        lv_obj_align(page.info, LV_ALIGN_LEFT_MID, kInfoX, 0);
    }

    page.date = lv_label_create(bar);
    lv_obj_set_style_text_font(page.date, kFontNormal, LV_PART_MAIN);
    lv_obj_set_style_text_color(page.date, lv_color_hex(kColorTextValue), LV_PART_MAIN);
    lv_label_set_text(page.date, "--");

    page.time = lv_label_create(bar);
    lv_obj_set_style_text_font(page.time, kFontTitle, LV_PART_MAIN);
    lv_obj_set_style_text_color(page.time, lv_color_hex(kColorText), LV_PART_MAIN);
    lv_label_set_text(page.time, "--:--");

    page.zone = lv_label_create(bar);
    lv_obj_set_style_text_font(page.zone, kFontNormal, LV_PART_MAIN);
    lv_obj_set_style_text_color(page.zone, lv_color_hex(kColorHighlight), LV_PART_MAIN);
    lv_label_set_text(page.zone, "");
    _alignClock(page);
    return page;
}

// one part of the clock, written into the buffer of the caller (nothing is written for a nullptr)
static void _formatClockPart(const char *format, struct tm &tm, char *output, size_t size)
{
    if (!output || !size) {
        return;
    }
    if (strftime(output, size, format, &tm) <= 0) {
        output[0] = 0;
    }
}

void formatClock(bool format24h, char *date, size_t dateSize, char *time, size_t timeSize, char *zone, size_t zoneSize)
{
    if (date && dateSize) {
        date[0] = 0;
    }
    if (time && timeSize) {
        time[0] = 0;
    }
    if (zone && zoneSize) {
        zone[0] = 0;
    }
    auto now = ::time(nullptr);
    if (now < 1600000000) { // clock not set yet (before 2020)
        return;
    }
    struct tm tm;
    localtime_r(&now, &tm);
    _formatClockPart("%a %b %d %Y", tm, date, dateSize);
    _formatClockPart(format24h ? "%H:%M" : "%I:%M %p", tm, time, timeSize);
    _formatClockPart("%Z", tm, zone, zoneSize);
}

void formatClock(bool format24h, String &date, String &time, String &zone)
{
    char dateBuffer[40];
    char timeBuffer[40];
    char zoneBuffer[40];
    formatClock(format24h, dateBuffer, sizeof(dateBuffer), timeBuffer, sizeof(timeBuffer), zoneBuffer, sizeof(zoneBuffer));
    date = dateBuffer;
    time = timeBuffer;
    zone = zoneBuffer;
}

void setClock(const PageRefs &page, bool format24h)
{
    if (!page.isValid()) {
        return;
    }
    String date;
    String time;
    String zone;
    formatClock(format24h, date, time, zone);
    if (page.date) {
        lv_label_set_text(page.date, date.length() ? date.c_str() : "--");
    }
    if (page.time) {
        lv_label_set_text(page.time, time.length() ? time.c_str() : "--:--");
    }
    if (page.zone) {
        lv_label_set_text(page.zone, zone.c_str());
    }
    // the labels are right aligned next to each other, their width changed with the text
    _alignClock(page);
}

