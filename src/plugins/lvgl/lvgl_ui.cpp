lv_coord_t getTextWidth(const char *text, const lv_font_t *font)
{
    if (!text || !font) {
        return 0;
    }
    lv_point_t size;
    lv_txt_get_size(&size, text, font, 0, 0, LV_COORD_MAX, LV_TEXT_FLAG_NONE);
    return size.x;
}

// width a label was given with lv_obj_set_width(), 0 when it uses the content size
static lv_coord_t _explicitWidth(lv_obj_t *label)
{
    if (label == nullptr) {
        return 0;
    }
    const auto width = lv_obj_get_style_width(label, LV_PART_MAIN);
    return (width > 0 && !LV_COORD_IS_SPEC(width)) ? width : 0;
}

// usable width for a label: the value the caller passed, or the width set with
// lv_obj_set_width() when it cannot be used yet. 0 means "no width known"
static lv_coord_t _usableWidth(lv_obj_t *label, lv_coord_t width)
{
    // The screens pass lv_obj_get_width() of the label. That is the size of the last layout
    // pass and still 0 while the widget tree was not laid out - the screens create and fill
    // their widgets in the same tick (the screen is shown), so using it would set the width of
    // the label to 0 and the text could never be displayed. The width that was set with
    // lv_obj_set_width() is the one lv_obj_get_width() returns after the next layout pass
    if (width > 0 && !LV_COORD_IS_SPEC(width)) {
        return width;
    }
    return _explicitWidth(label);
}

// index of a font inside kFontLadder (sorted from large to small). A font that is not part of
// the ladder gets the first entry that is not larger than it
static uint8_t _ladderIndex(const lv_font_t *font)
{
    for (uint8_t i = 0; i < kFontLadderSize; i++) {
        if (kFontLadder[i] == font) {
            return i;
        }
    }
    for (uint8_t i = 0; i < kFontLadderSize; i++) {
        if (kFontLadder[i]->line_height <= font->line_height) {
            return i;
        }
    }
    return static_cast<uint8_t>(kFontLadderSize - 1);
}

// distance of the baseline from the top of the line (the same calculation lv_draw_label uses)
static lv_coord_t _baseline(const lv_font_t *font)
{
    return static_cast<lv_coord_t>(font->line_height - font->base_line - font->underline_position);
}

// sets the text of a label, the size and the long mode. The largest font that may be used is
// the one the label was created with unless allowGrow is set (fitText picks the largest font
// that fits, fitTextDown only shrinks). If no font fits the text is cut off with an ellipsis or
// it scrolls slowly
static lv_obj_t *_applyText(lv_obj_t *label, const char *text, lv_coord_t maxWidth, bool allowScroll,
                            bool allowGrow, bool &fits)
{
    fits = false;
    if (!label) {
        return label;
    }
    text = text ? text : "";
    maxWidth = _usableWidth(label, maxWidth);
    if (maxWidth > 0) {
        lv_obj_set_width(label, maxWidth);
    }
    else {
        // no width known (the label was not resized and has no explicit width): only measure,
        // do not resize the label
        maxWidth = LV_COORD_MAX;
    }
    const uint8_t start = allowGrow ? 0 : _ladderIndex(lv_obj_get_style_text_font(label, LV_PART_MAIN));
    for (uint8_t i = start; i < kFontLadderSize; i++) {
        auto font = kFontLadder[i];
        if (getTextWidth(text, font) <= maxWidth) {
            lv_obj_set_style_text_font(label, font, LV_PART_MAIN);
            lv_label_set_long_mode(label, LV_LABEL_LONG_DOT);
            lv_label_set_text(label, text);
            fits = true;
            return label;
        }
    }
    // no font fits: smallest font, ellipsis or a slow circular scroll
    lv_obj_set_style_text_font(label, kFontSmall, LV_PART_MAIN);
    if (allowScroll) {
        lv_label_set_long_mode(label, LV_LABEL_LONG_SCROLL_CIRCULAR);
        // scroll speed is a style property in LVGL 8.3+, 25 px/s is slow on purpose
        lv_obj_set_style_anim_speed(label, 25, LV_PART_MAIN);
    }
    else {
        lv_label_set_long_mode(label, LV_LABEL_LONG_DOT);
    }
    lv_label_set_text(label, text);
    return label;
}

// shrinks the font until the text fits, the current font is never increased. Used for labels
// with a size of its own (labels of a fixed layout, keys of a key/value list): fitText() picks
// the largest font that fits, which would turn short text into very large text
bool fitTextDown(lv_obj_t *label, const char *text, lv_coord_t maxWidth, bool allowScroll)
{
    bool fits;
    _applyText(label, text, maxWidth, allowScroll, false, fits);
    return fits;
}

bool fitText(lv_obj_t *label, const char *text, lv_coord_t maxWidth)
{
    bool fits;
    _applyText(label, text, maxWidth, false, true, fits);
    return fits;
}

bool fitTextOrScroll(lv_obj_t *label, const char *text, lv_coord_t maxWidth)
{
    bool fits;
    _applyText(label, text, maxWidth, true, true, fits);
    return fits;
}

void layoutCenteredPair(lv_obj_t *name, lv_obj_t *date, const char *nameText, const char *dateText,
                        lv_coord_t width, lv_coord_t gap)
{
    if (!name || !date || width <= 0) {
        return;
    }
    nameText = nameText ? nameText : "";
    dateText = dateText ? dateText : "";
    if (gap < 0) {
        gap = 0;
    }

    // the font a label was created with is the largest one it may use, both shrink together
    // until the pair fits (the larger one is shrunk first)
    uint8_t nameIndex = _ladderIndex(lv_obj_get_style_text_font(name, LV_PART_MAIN));
    uint8_t dateIndex = _ladderIndex(lv_obj_get_style_text_font(date, LV_PART_MAIN));
    lv_coord_t nameWidth = 0;
    lv_coord_t dateWidth = 0;
    for (uint8_t i = 0; i < (kFontLadderSize * 2); i++) {
        nameWidth = getTextWidth(nameText, kFontLadder[nameIndex]);
        dateWidth = getTextWidth(dateText, kFontLadder[dateIndex]);
        if ((nameWidth + gap + dateWidth) <= width) {
            break;
        }
        if (nameIndex == dateIndex) {
            if ((nameIndex + 1) >= kFontLadderSize) {
                break;
            }
            nameIndex++;
            dateIndex++;
        }
        else if (nameIndex < dateIndex) {
            nameIndex++; // the name uses the larger font
        }
        else {
            dateIndex++; // the date uses the larger font
        }
    }
    if ((nameWidth + gap + dateWidth) > width) {
        // even the smallest font is too large, both get half of the row and are cut off
        nameWidth = static_cast<lv_coord_t>((width - gap) / 2);
        dateWidth = static_cast<lv_coord_t>(width - gap - nameWidth);
    }

    const auto nameFont = kFontLadder[nameIndex];
    const auto dateFont = kFontLadder[dateIndex];
    lv_obj_set_style_text_font(name, nameFont, LV_PART_MAIN);
    lv_obj_set_style_text_font(date, dateFont, LV_PART_MAIN);
    lv_label_set_long_mode(name, LV_LABEL_LONG_DOT);
    lv_label_set_long_mode(date, LV_LABEL_LONG_DOT);
    lv_obj_set_size(name, nameWidth, lv_font_get_line_height(nameFont));
    lv_obj_set_size(date, dateWidth, lv_font_get_line_height(dateFont));

    // the name keeps its position and is the left edge of the pair, the date is aligned to the
    // baseline of the name so both sit on the same line.
    // lv_obj_get_x/y() would return the coordinates of the last layout pass (still 0 while the
    // widget tree is built and filled in the same tick), the values lv_obj_set_pos() wrote are
    // the style properties.
    // The pair is moved with the translation styles and NOT with lv_obj_set_pos(): the style x/y
    // has to keep the position the labels were created with. lv_obj_set_pos() would store the
    // centered position in the style, the next call would use it as the new left edge of the pair
    // and the pair would move one step further out of the row with every update - the screens
    // refresh once per second, so it is out of the window after a few seconds
    const auto left = lv_obj_get_style_x(name, LV_PART_MAIN);
    const auto top = lv_obj_get_style_y(name, LV_PART_MAIN);
    const auto dateLeft = lv_obj_get_style_x(date, LV_PART_MAIN);
    const auto dateTop = lv_obj_get_style_y(date, LV_PART_MAIN);
    const auto x = static_cast<lv_coord_t>(LV_COORD_IS_SPEC(left) ? 0 : left);
    const auto y = static_cast<lv_coord_t>(LV_COORD_IS_SPEC(top) ? 0 : top);
    const auto offset = static_cast<lv_coord_t>((width - nameWidth - gap - dateWidth) / 2);
    lv_obj_set_style_translate_x(name, offset, LV_PART_MAIN);
    lv_obj_set_style_translate_y(name, 0, LV_PART_MAIN);
    lv_obj_set_style_translate_x(date,
                                 static_cast<lv_coord_t>(x + offset + nameWidth + gap - (LV_COORD_IS_SPEC(dateLeft) ? 0 : dateLeft)),
                                 LV_PART_MAIN);
    lv_obj_set_style_translate_y(date,
                                 static_cast<lv_coord_t>(y + _baseline(nameFont) - _baseline(dateFont) - (LV_COORD_IS_SPEC(dateTop) ? 0 : dateTop)),
                                 LV_PART_MAIN);
    lv_label_set_text(name, nameText);
    lv_label_set_text(date, dateText);
}

void setText(lv_obj_t *label, const char *text, const lv_font_t *font, uint32_t color)
{
    if (!label) {
        return;
    }
    if (font) {
        lv_obj_set_style_text_font(label, font, LV_PART_MAIN);
    }
    lv_obj_set_style_text_color(label, lv_color_hex(color), LV_PART_MAIN);
    lv_label_set_text(label, text ? text : "");
}

