void setTileState(lv_obj_t *tile, TileState state, bool filled)
{
    if (!tile) {
        return;
    }
    auto border = kColorBorder;
    auto background = kColorCard;
    switch (state) {
    case TileState::ON:
        border = kColorActive;
        if (filled) {
            // an active tile is a filled card, the texts are drawn white by the screen
            background = kColorActive;
        }
        break;
    case TileState::PENDING:
        // An action is on its way: the accent border is the mark. The fill follows the state the
        // tile shows - the action was applied to the model right away (optimistic, see
        // Dashboard::toggle()), so a tile that the user switched on is filled while the entity has
        // not confirmed it yet (filled = the tile shows an active state)
        border = kColorAccent;
        background = filled ? kColorActive : kColorCardAlt;
        break;
    case TileState::UNAVAILABLE:
        // darker card: a tile has no outline, the mark has to be the fill
        border = kColorError;
        background = kColorCardAlt;
        break;
    default:
        break;
    }
    lv_obj_set_style_border_color(tile, lv_color_hex(border), LV_PART_MAIN);
    lv_obj_set_style_bg_color(tile, lv_color_hex(background), LV_PART_MAIN);
}

