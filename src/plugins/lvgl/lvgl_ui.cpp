// font an icon is drawn with. There are two sizes only, everything else is rounded to them
static const lv_font_t *_iconFont(lv_coord_t size)
{
    return (size <= kIconSizeSmall) ? &lv_font_mdi_20 : &lv_font_mdi_48;
}


