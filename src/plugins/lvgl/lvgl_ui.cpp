// Rotation: a 300 degree arc with the gap on the right and the head of the arrow beside it. The MDI
// subset fonts have no glyph for it, a circular arrow is a few arcs of LVGL
lv_obj_t *createRotateIcon(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t size, uint32_t color)
{
    auto icon = _container(parent, x, y, size, size);
    lv_obj_clear_flag(icon, LV_OBJ_FLAG_CLICKABLE);
    const auto band = static_cast<lv_coord_t>((size >= 32) ? 5 : 2);
    auto arc = lv_arc_create(icon);
    lv_obj_set_size(arc, size, size);
    lv_obj_set_pos(arc, 0, 0);
    // the gap is on the right side, where the head of the arrow sits
    lv_arc_set_rotation(arc, 45);
    lv_arc_set_bg_angles(arc, 0, 300);
    lv_arc_set_mode(arc, LV_ARC_MODE_NORMAL);
    lv_arc_set_value(arc, 0);
    lv_obj_set_style_arc_width(arc, band, LV_PART_MAIN);
    lv_obj_set_style_arc_color(arc, lv_color_hex(color), LV_PART_MAIN);
    lv_obj_set_style_arc_width(arc, 0, LV_PART_INDICATOR);
    lv_obj_set_style_bg_opa(arc, LV_OPA_TRANSP, LV_PART_MAIN);
    lv_obj_set_style_border_width(arc, 0, LV_PART_MAIN);
    lv_obj_set_style_pad_all(arc, 0, LV_PART_MAIN);
    lv_obj_set_style_bg_opa(arc, LV_OPA_TRANSP, LV_PART_KNOB);
    lv_obj_set_style_pad_all(arc, 0, LV_PART_KNOB);
    lv_obj_clear_flag(arc, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_clear_flag(arc, LV_OBJ_FLAG_SCROLLABLE);
    // the head of the arrow, at the upper end of the arc (45 + 300 = 345 degrees)
    const auto head = band * 3;
    auto disc = _disc(icon, static_cast<lv_coord_t>(size - head), static_cast<lv_coord_t>(size / 2 - head), head, color);
    lv_obj_clear_flag(disc, LV_OBJ_FLAG_CLICKABLE);
    return icon;
}

lv_obj_t *createMoon(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t size)
{
    return _moon(parent, x, y, size);
}

void setMoonPhase(lv_obj_t *moon, float illumination, bool waxing)
{
    if (!moon || lv_obj_get_child_cnt(moon) == 0) {
        return;
    }
    if (illumination < 0) {
        illumination = 0;
    }
    else if (illumination > 1) {
        illumination = 1;
    }
    auto shadow = lv_obj_get_child(moon, 0);
    // lv_obj_get_width() is the size of the last layout pass and 0 while the widget tree was not
    // laid out yet - the screen is created and filled in the same tick, so the disc would not move
    // for the first update. createMoon() sets the size of the disc explicitly, use that one
    auto size = _explicitWidth(moon);
    if (size <= 0) {
        return;
    }
    // waxing = lit on the right, the shadow moves to the left (and out of the disc for a full moon)
    auto offset = static_cast<lv_coord_t>(size * illumination * (waxing ? -2.0f : 2.0f));
    lv_obj_set_pos(shadow, offset, 0);
}

