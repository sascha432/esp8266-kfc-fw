static void _drawIcon(lv_obj_t *parent, IconType type, lv_coord_t size, uint32_t color = kIconColorDefault)
{
    const auto index = static_cast<uint8_t>(type);
    if (index >= kIconCount) {
        return;
    }
    auto label = lv_label_create(parent);
    // the glyph font has to be set before the text: the label lays the text out with the font of
    // its style as soon as the text is set
    lv_obj_set_style_text_font(label, _iconFont(size), LV_PART_MAIN);
    lv_obj_set_style_text_color(label, lv_color_hex(color ? color : kIconColor[index]), LV_PART_MAIN);
    lv_obj_set_style_pad_all(label, 0, LV_PART_MAIN);
    lv_label_set_text(label, kIconGlyph[index]);
    lv_obj_center(label);
}

