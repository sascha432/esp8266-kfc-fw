// creates an icon container with the icon inside, size x size pixels at x,y. Use kIconSizeSmall or
// kIconSizeLarge, the glyph is centered in the container. color 0 uses the theme color of the icon
lv_obj_t *createIcon(lv_obj_t *parent, IconType type, lv_coord_t x, lv_coord_t y, lv_coord_t size,
                     uint32_t color = kIconColorDefault);

// redraws an icon container created by createIcon()
void setIcon(lv_obj_t *icon, IconType type, lv_coord_t size, uint32_t color = kIconColorDefault);

// true when the container already draws the glyph of `type`. setIcon() rebuilds the label, so a
// caller that redraws an icon on every update skips it while the glyph does not change
bool isIcon(lv_obj_t *icon, IconType type);

// recolors the glyph of an icon, a filled (active) tile or button draws its icons white
void setIconColor(lv_obj_t *icon, uint32_t color);

// button with an icon in the middle and no label, used by the climate mode bar
lv_obj_t *createIconButton(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h,
                           IconType type, lv_coord_t iconSize);

// house icon used by the indoor screen
lv_obj_t *createHouseIcon(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t size);

// Circular arrow of the rotate setting: a 300 degree arc with the gap on the right and the head of
// the arrow beside it (also drawn with lv_arc, the MDI subset fonts have no glyph for it)
lv_obj_t *createRotateIcon(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t size, uint32_t color = kColorTextValue);

// moon disc: a light circle with a dark circle clipped to it. The shadow is moved by
// setMoonPhase(), illumination 0 = new moon, 0.5 = half, 1 = full
lv_obj_t *createMoon(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t size);
void setMoonPhase(lv_obj_t *moon, float illumination, bool waxing);

