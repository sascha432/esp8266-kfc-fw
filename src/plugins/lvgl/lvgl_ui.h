// ------------------------------------------------------------------------------------------
// text
// ------------------------------------------------------------------------------------------
// measures the width of a single line of text
lv_coord_t getTextWidth(const char *text, const lv_font_t *font);

// sets the text and shrinks the font until it fits into maxWidth. If no font fits the text is
// cut off with an ellipsis. Returns true if the text fits without being cut off
bool fitText(lv_obj_t *label, const char *text, lv_coord_t maxWidth);

// same as fitText() but the font of the label is never increased - it is the maximum. Use it
// for text with a size of its own (labels of a fixed layout, keys of a key/value list), fitText()
// picks the largest font that fits, which turns short text into very large text.
// allowScroll keeps the smallest font and scrolls the text slowly instead of cutting it off with
// an ellipsis. Use it for the few values that can be arbitrarily long (host names, SSIDs).
// maxWidth 0 uses the width that was set with lv_obj_set_width()
bool fitTextDown(lv_obj_t *label, const char *text, lv_coord_t maxWidth = 0, bool allowScroll = false);

// same as fitText() but scrolls the text slowly (circular) if it does not fit in any font.
// Use it for the few strings that can be arbitrarily long (descriptions, hostnames), not for
// short values - scrolling text is hard to read and should stay the exception
bool fitTextOrScroll(lv_obj_t *label, const char *text, lv_coord_t maxWidth);

// sets the text without measuring, with a fixed font and color
void setText(lv_obj_t *label, const char *text, const lv_font_t *font = nullptr, uint32_t color = kColorText);

// Places two labels of one row next to each other in the middle of a row of `width` pixels
// ("name" on the left, "date" on the right, separated by `gap`). The y of the name label is the
// top of the row, the date is put on the same baseline. Both fonts are their maximum, they
// shrink together until the pair fits and are cut off if even the smallest font is too large.
// Used by the moon phase rows
void layoutCenteredPair(lv_obj_t *name, lv_obj_t *date, const char *nameText, const char *dateText,
                        lv_coord_t width, lv_coord_t gap);

// ------------------------------------------------------------------------------------------
// widgets
// ------------------------------------------------------------------------------------------
// handles of the page created by createPage()
struct PageRefs {
    lv_obj_t *root{nullptr};
    lv_obj_t *date{nullptr};
    lv_obj_t *time{nullptr};
    lv_obj_t *zone{nullptr};
    lv_obj_t *title{nullptr};
    lv_obj_t *info{nullptr};

    // true if the page has been created
    bool isValid() const {
        return root != nullptr;
    }
};

// creates the page background and the top bar: the title (and the optional info text) on the
// left, the date, the time and the time zone right aligned. The content area starts below the
// bar (LVGLUI::kBarHeight) and ends above the footer (height - kFooterHeight). A tap in the bar
// is handled by the screen manager, it always opens the screen overview
PageRefs createPage(lv_obj_t *parent, const char *title, const char *right = nullptr);

// refreshes date/time/timezone of the top bar from the local time
void setClock(const PageRefs &page, bool format24h);

// formats the current local time, empty strings if the clock is not set yet
void formatClock(bool format24h, String &date, String &time, String &zone);

// creates a footer strip and returns it as the parent for footer content
lv_obj_t *createFooter(lv_obj_t *parent);

// Plain transparent container without background, border, radius or padding, not scrollable.
// Use it as the parent of content that is rebuilt while the page around it stays: clear it with
// lv_obj_clean() and build the new content below it. The position is relative to parent, like
// every other widget created by these helpers
lv_obj_t *createContainer(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h);

// card with optional title in the upper left corner, content can be added as a child
lv_obj_t *createCard(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h,
                     const char *title = nullptr);

// label at an absolute position, width is set to maxWidth if it is not LV_SIZE_CONTENT
lv_obj_t *addLabel(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, const char *text,
                   const lv_font_t *font, uint32_t color, lv_coord_t maxWidth = LV_SIZE_CONTENT,
                   lv_text_align_t align = LV_TEXT_ALIGN_LEFT);

// 1 px separator line
lv_obj_t *addSeparator(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w);

// "label" on the left and "value" on the right, used by key/value lists
struct KeyValueRefs {
    lv_obj_t *key{nullptr};
    lv_obj_t *value{nullptr};
};

// adds one key/value row, both labels fit their part of the width (the value shrinks first).
// keyWidth 0 gives the key 45% of the row, a fixed width is used to lay several rows out with
// one value column (the key then takes only the space its longest entry needs)
KeyValueRefs addKeyValue(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t gap,
                         const char *key, const char *value, lv_coord_t keyWidth = 0);

// ------------------------------------------------------------------------------------------
// tiles, arcs and buttons of an application dashboard
// ------------------------------------------------------------------------------------------
// state of a tile, drawn with the border and the background of setTileState()
enum class TileState : uint8_t {
    OFF,          // inactive
    ON,           // active/on
    PENDING,      // an action was sent and is not confirmed yet
    UNAVAILABLE,  // no value or the entity is not available
};

// card that fills the cells of a tile, the content is added as a child. The state is drawn with
// setTileState(). filled = false keeps the card background and only colors the border, for tiles
// that show their state with a fill or with bars (a dimmer or a climate tile)
lv_obj_t *createTile(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h);
void setTileState(lv_obj_t *tile, TileState state, bool filled = true);

// Image of a tile (the camera preview of a picture tile). The pixels belong to the caller: it
// keeps a lv_img_dsc_t with LV_IMG_CF_TRUE_COLOR (RGB565, where red/blue depend on
// LV_COLOR_16_SWAP) and sets it with lv_img_set_src(image, &descriptor). The image is created
// without a source, which has to be exactly w x h pixels
lv_obj_t *createImage(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h);

// arc of a dashboard tile: 270 degrees with the gap centered at the bottom, value range 0..100.
// The arc can be dragged by the user, the value is read with lv_arc_get_value()
static constexpr uint16_t kArcRotation = 135;
// thickness of the ring (the track and the indicator). LVGL has no knob size of its own, it draws
// the knob as a circle of arc_width + 2 x pad (LV_PART_KNOB), see createArc()
static constexpr lv_coord_t kArcWidth = 18;
// `ringWidth` is the thickness of the ring (the track and the indicator), the knob follows it
lv_obj_t *createArc(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t size, lv_coord_t ringWidth = kArcWidth);
// sets the value and the color of the indicator, the knob stays white like on the Home Assistant
// thermostat card
void setArcValue(lv_obj_t *arc, int16_t value, uint32_t color = kColorAccent);

// small button with a centered label (the label is the first child of the object). An empty text
// creates a button without a label, use createIconButton() for one with an icon inside
lv_obj_t *createButton(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h,
                       const char *text, const lv_font_t *font = nullptr);

// active buttons are filled with the accent color, inactive ones are plain cards. A label of the
// button (if it has one) switches to a dark text color while it is active
void setButtonActive(lv_obj_t *button, bool active);

// Level fill of a dimmer tile or of a panel slider: a rounded bar that grows from the bottom of a
// track (x, y, w, trackHeight). The track itself stays empty, the fill is the visible level
// level fill of a dashboard tile (the level of a dimmer that is dragged): the height follows the
// level, so only the edge that moves is seen as a shape of its own - the other end is clipped by the
// rounded tile (see createLevelFill()). The edge that moves is nearly square
static constexpr lv_coord_t kLevelFillRadius = 5;
lv_obj_t *createLevelFill(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h);
void setLevelFill(lv_obj_t *fill, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t trackHeight,
                  uint8_t percent, uint32_t color = kColorActive);

// Scrollable list of the panels (option and effect list): a card with a scrollbar on the right,
// the items are added by the caller with addListItem() and placed in their own coordinates
lv_obj_t *createList(lv_obj_t *parent, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h);
// one item of a list, a card with a centered label
lv_obj_t *addListItem(lv_obj_t *list, lv_coord_t x, lv_coord_t y, lv_coord_t w, lv_coord_t h, const char *text);
// the item that is set is filled like an active tile, the label stays white
void setListItemActive(lv_obj_t *item, bool active);

// removes LV_OBJ_FLAG_CLICKABLE from the object and all children, so that a click reaches the
// tile below it (every object created with lv_obj_create() is clickable by default)
void clearClickable(lv_obj_t *obj);

